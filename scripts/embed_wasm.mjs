// scripts/embed_wasm.mjs
import fs from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const wasmDir = path.resolve(rootDir, "wasm");
const wasmPath = path.resolve(wasmDir, "target/wasm32-unknown-unknown/release/color_math_wasm.wasm");
const outPath = path.resolve(rootDir, "src/parsers/wasm_binary.ts");

function getLatestSourceMtime(dir) {
  let latest = 0;
  if (!fs.existsSync(dir)) return latest;

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "target") {
        const sub = getLatestSourceMtime(fullPath);
        if (sub > latest) latest = sub;
      }
    } else if (entry.isFile() && (entry.name.endsWith(".rs") || entry.name === "Cargo.toml")) {
      const stat = fs.statSync(fullPath);
      if (stat.mtimeMs > latest) latest = stat.mtimeMs;
    }
  }
  return latest;
}

function checkCargoAvailable() {
  try {
    execSync("cargo --version", { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

// Phase 1: AOT Staleness Audit
const latestSourceMtime = getLatestSourceMtime(wasmDir);
const wasmExists = fs.existsSync(wasmPath);
const wasmMtime = wasmExists ? fs.statSync(wasmPath).mtimeMs : 0;

if (latestSourceMtime > wasmMtime || !wasmExists) {
  if (latestSourceMtime > 0) {
    console.log(`[WASM Embed] Stale or missing WASM binary detected (Source mtime: ${new Date(latestSourceMtime).toISOString()}).`);
    if (checkCargoAvailable()) {
      console.log(`[WASM Embed] Compiling WebAssembly core via 'cargo build --target wasm32-unknown-unknown --release'...`);
      try {
        execSync("cargo build --target wasm32-unknown-unknown --release", {
          cwd: wasmDir,
          stdio: "inherit",
        });
        console.log(`[WASM Embed] ✔ Rust WASM compilation successful.`);
      } catch (err) {
        console.error(`[WASM Embed] ❌ Cargo compilation failed: ${err.message}`);
      }
    } else {
      console.warn(`[WASM Embed] Warning: cargo is not available in PATH. Skipping AOT recompilation.`);
    }
  }
}

// Phase 2: Base64 Serialization & Atomic Inlining
if (fs.existsSync(wasmPath)) {
  const bytes = fs.readFileSync(wasmPath);
  const b64 = bytes.toString("base64");
  const content = `// Auto-generated by scripts/embed_wasm.mjs - do not edit manually\nexport const WASM_BASE64 = "${b64}";\n`;
  
  let currentContent = "";
  if (fs.existsSync(outPath)) {
    currentContent = fs.readFileSync(outPath, "utf8");
  }

  if (currentContent !== content) {
    fs.writeFileSync(outPath, content, "utf8");
    console.log(`[WASM Embed] Successfully embedded ${bytes.length} bytes into ${outPath}`);
  } else {
    console.log(`[WASM Embed] Embedded WASM fixture is up-to-date (${bytes.length} bytes).`);
  }
} else {
  console.warn(`[WASM Embed] Warning: ${wasmPath} not found! Preserving existing embedded fixture.`);
}
