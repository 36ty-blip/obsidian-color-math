// scripts/embed_wasm.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const wasmPath = path.resolve(__dirname, "../wasm/target/wasm32-unknown-unknown/release/color_math_wasm.wasm");
const outPath = path.resolve(__dirname, "../src/parsers/wasm_binary.ts");

if (fs.existsSync(wasmPath)) {
  const bytes = fs.readFileSync(wasmPath);
  const b64 = bytes.toString("base64");
  const content = `// Auto-generated by scripts/embed_wasm.mjs - do not edit manually\nexport const WASM_BASE64 = "${b64}";\n`;
  fs.writeFileSync(outPath, content, "utf8");
  console.log(`[WASM Embed] Successfully embedded ${bytes.length} bytes into ${outPath}`);
} else {
  console.warn(`[WASM Embed] Warning: ${wasmPath} not found!`);
}
