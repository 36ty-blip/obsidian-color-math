#!/usr/bin/env node
// scripts/generate_constructors.mjs
// Single Source of Truth Code Generator for Mathematical Syntactic Sugar & Constructors.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");

const jsonPath = path.join(rootDir, "src", "config", "constructors.json");
const rawJson = fs.readFileSync(jsonPath, "utf-8");
const config = JSON.parse(rawJson);

const envMap = config.environments;
const otherConstructors = config.otherConstructors || [];

// Sort keys by descending length so longer prefixes match first (e.g. "aligned" before "align")
const envKeysSorted = Object.keys(envMap).sort((a, b) => b.length - a.length || a.localeCompare(b));
const allConstructors = [...envKeysSorted, ...otherConstructors].sort((a, b) => b.length - a.length || a.localeCompare(b));

const envAlternation = envKeysSorted.join("|");
const allAlternation = allConstructors.join("|");

// 1. Generate TypeScript definitions
const tsContent = `// Auto-generated by scripts/generate_constructors.mjs - DO NOT EDIT MANUALLY
// Single Source of Truth: src/config/constructors.json

export const MATRIX_SUGAR_PREFIXES: Record<string, string> = ${JSON.stringify(envMap, null, 2)};

export const ENVIRONMENT_NAMES = ${JSON.stringify(envKeysSorted)} as const;

export const OTHER_CONSTRUCTORS = ${JSON.stringify(otherConstructors)} as const;

export const ALL_CONSTRUCTOR_NAMES = ${JSON.stringify(allConstructors)} as const;

export const CONSTRUCTOR_SET: ReadonlySet<string> = new Set(ALL_CONSTRUCTOR_NAMES);

/**
 * Fast-path gating regex used by normalizeMathSyntax to detect if any constructor prefix is present.
 */
export const CONSTRUCTOR_GATING_RE = /(?:^|[^A-Za-z0-9_])\\\\?(?:${allAlternation})\\s*[{[]/;

/**
 * Lookahead regex used by delimiter auto-sizing to detect if a matrix/environment immediately follows.
 */
export const PRECEDING_MATRIX_RE = /^\\\\?(?:${envAlternation})\\s*[{[]/;

/**
 * Sticky regex used by parser tokenizers to consume constructor keywords atomically without letter fragmentation.
 */
export const SUGAR_CONSTRUCTOR_STICKY_RE = /(?:${allAlternation})(?![A-Za-z])/y;

/**
 * Word-boundary regex used by variable hash to prevent constructor letters from being hashed as variables.
 */
export const SUGAR_CONSTRUCTOR_WORD_RE = /^(?:${allAlternation})(?![A-Za-z])/;

/**
 * Regex matching unwrapped matrix prefix in normalizeBracketMatrices.
 */
export const MATRIX_PREFIX_UNWRAPPED_RE = /^(${envAlternation})\\s*([{[])/;

/**
 * Regex matching wrapped matrix prefix in normalizeBracketMatrices.
 */
export const MATRIX_PREFIX_WRAPPED_RE = /^\\s*\\\\?(${envAlternation})\\s*([{[])/;

/**
 * Regex matching backslashed matrix prefix in normalizeBracketMatrices.
 */
export const MATRIX_PREFIX_BACKSLASHED_RE = /^\\\\(${envAlternation})\\s*([{[])/;
`;

const tsOutputPath = path.join(rootDir, "src", "config", "constructors.generated.ts");
fs.writeFileSync(tsOutputPath, tsContent, "utf-8");
console.log(`[Constructors Generator] Successfully generated ${tsOutputPath}`);

// 2. Generate Rust WebAssembly definitions
const rustArms = envKeysSorted.map((k, idx) => {
  const target = envMap[k];
  const prefix = idx === 0 ? "if" : "} else if";
  return `    ${prefix} starts_with_ascii(slice, i, b"${k}") {\n        Some((b"${target}", i + ${k.length}))`;
}).join("\n");

const rustContent = `// Auto-generated by scripts/generate_constructors.mjs - DO NOT EDIT MANUALLY
// Single Source of Truth: src/config/constructors.json

#[inline]
pub fn match_generated_matrix_prefix(slice: &[u16], i: usize) -> Option<(&'static [u8], usize)> {
${rustArms}
    } else {
        None
    }
}
`;

const rustOutputPath = path.join(rootDir, "wasm", "src", "constructors_generated.rs");
fs.writeFileSync(rustOutputPath, rustContent, "utf-8");
console.log(`[Constructors Generator] Successfully generated ${rustOutputPath}`);
